// Scans assets/brands/*.png|jpg|webp and writes src/data/brand-logos.ts (React Native needs static require()s).
import { readdirSync, writeFileSync } from 'node:fs';

const files = readdirSync(new URL('../assets/brands/', import.meta.url)).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort();
const lines = files.map((f) => `  ${JSON.stringify(f.replace(/\.[^.]+$/, '').toLowerCase())}: require('../../assets/brands/${f}'),`);
writeFileSync(new URL('../src/data/brand-logos.ts', import.meta.url), `// GENERATED by scripts/gen-brand-logos.mjs — do not edit. Add files to assets/brands/ and run \`npm run brand-logos\`.
/* eslint-disable */
export const BRAND_LOGOS: Record<string, number> = {
${lines.join('\n')}
};
`);
console.log(`brand-logos: ${files.length} logo(s)`);
